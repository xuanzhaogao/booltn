#!/usr/bin/env python3
"""Generate wgmma_u8.inc: wrappers for wgmma.m64nNk32.s32.u8.u8, N in {64,128,256}."""
out = ["// AUTO-GENERATED by gen_wgmma_u8.py", "#pragma once"]
for n in (64, 128, 256):
    nr = n // 2
    regs = ",".join(f"%{i}" for i in range(nr))
    outs = ", ".join(f'"+r"(d[{i}])' for i in range(nr))
    out.append(f"""__device__ __forceinline__ void wgmma_u8_n{n}(int (&d)[{nr}], uint64_t da, uint64_t db, int scale_d) {{
  asm volatile("{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nr+2}, 0;\\n"
    "wgmma.mma_async.sync.aligned.m64n{n}k32.s32.u8.u8 {{{regs}}}, %{nr}, %{nr+1}, p;\\n}}\\n"
    : {outs}
    : "l"(da), "l"(db), "r"(scale_d));
}}""")
out.append("""template <int BN> struct WgmmaU8;
template <> struct WgmmaU8<64>  { static __device__ __forceinline__ void run(int (&d)[32],  uint64_t a, uint64_t b, int s) { wgmma_u8_n64(d, a, b, s); } };
template <> struct WgmmaU8<128> { static __device__ __forceinline__ void run(int (&d)[64],  uint64_t a, uint64_t b, int s) { wgmma_u8_n128(d, a, b, s); } };
template <> struct WgmmaU8<256> { static __device__ __forceinline__ void run(int (&d)[128], uint64_t a, uint64_t b, int s) { wgmma_u8_n256(d, a, b, s); } };""")
open("wgmma_u8.inc", "w").write("\n".join(out) + "\n")
